/** Generate a version-pinned offline shell from the exact production assets. */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import { resolve, relative, sep } from "node:path";

const directory = resolve(process.argv[2] ?? "dist");
const walk = async (directory) =>
  (
    await Promise.all(
      (await readdir(directory, { withFileTypes: true })).map(async (entry) => {
        const path = resolve(directory, entry.name);
        return entry.isDirectory() ? walk(path) : [path];
      }),
    )
  ).flat();
const indexPath = resolve(directory, "index.html");
let html = (await readFile(indexPath, "utf8")).replace(
  /\s*<meta name="biomechanics-build" content="[a-f0-9]+"\s*\/?>(\r?\n)?/g,
  "\n",
);
const files = (await walk(directory))
  .filter(
    (file) =>
      !["sw.js", ".DS_Store"].includes(relative(directory, file)) &&
      !file.endsWith(".map"),
  )
  .sort();
const required = [
  "index.html",
  "manifest.webmanifest",
  "icons/icon-192.png",
  "icons/icon-512.png",
];
for (const path of required) await stat(resolve(directory, path));
const hash = createHash("sha256");
for (const path of files)
  hash
    .update(relative(directory, path))
    .update(path === indexPath ? html : await readFile(path));
const version = hash.digest("hex").slice(0, 20);
html = html.replace(
  "</head>",
  `  <meta name="biomechanics-build" content="${version}" />\n  </head>`,
);
await writeFile(indexPath, html);
const precache = files.map((file) =>
  relative(directory, file).split(sep).join("/"),
);
const source = `/* Generated by scripts/generate-sw.mjs. Do not edit build output. */
const VERSION = ${JSON.stringify(version)};
const PREFIX = 'biomechanics-shell-';
const CACHE = PREFIX + VERSION;
const ASSETS = ${JSON.stringify(precache)};
const BASE = new URL('./', self.location.href);
const assetURL = path => new URL(path, BASE).href;
const INDEX = assetURL('index.html');
const ASSET_URLS = new Set(ASSETS.map(assetURL));

self.addEventListener('install', event => {
  // If even one file is unavailable, this version never becomes offline-ready.
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    try {
      await Promise.all(ASSETS.map(async path => {
        const request = new Request(assetURL(path), { cache: 'reload', credentials: 'same-origin' });
        const response = await fetch(request);
        if (!response.ok || response.type === 'opaque') throw new Error('Cannot cache ' + path);
        if (path === 'index.html' && !(await response.clone().text()).includes('name="biomechanics-build" content="' + VERSION + '"')) {
          throw new Error('The published build changed during offline preparation. Reload online to retry.');
        }
        await cache.put(assetURL(path), response);
      }));
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
  })());
  // Existing clients retain their running version until the update button is used.
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = (await caches.keys()).filter(name => name.startsWith(PREFIX));
    const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    const versions = await Promise.all(clients.map(client => new Promise(resolve => {
      const channel = new MessageChannel();
      const timeout = setTimeout(() => { channel.port1.close(); resolve(null); }, 1200);
      channel.port1.onmessage = message => {
        clearTimeout(timeout);
        channel.port1.close();
        resolve(typeof message.data?.version === 'string' ? message.data.version : null);
      };
      client.postMessage({ type: 'GET_CLIENT_BUILD' }, [channel.port2]);
    })));
    // Keep every build still used by an open tab. If a client cannot identify its
    // build yet, retain old caches until a later activation can verify them.
    if (versions.every(Boolean)) {
      const retained = new Set([CACHE, ...versions.map(version => PREFIX + version)]);
      await Promise.all(names.filter(name => !retained.has(name)).map(name => caches.delete(name)));
    }
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
  if (event.data?.type === 'CACHE_STATUS' || event.data?.type === 'REPAIR_CACHE') {
    event.waitUntil((async () => {
      const cache = await caches.open(CACHE);
      let error = null;
      if (event.data.type === 'REPAIR_CACHE') {
        try {
          await Promise.all(ASSETS.map(async path => {
            if (await cache.match(assetURL(path))) return;
            const response = await fetch(new Request(assetURL(path), { cache: 'reload', credentials: 'same-origin' }));
            if (!response.ok || response.type === 'opaque') throw new Error('Cannot restore ' + path);
            if (path === 'index.html' && !(await response.clone().text()).includes('name="biomechanics-build" content="' + VERSION + '"')) {
              throw new Error('A newer app build is available. Apply its update to prepare offline access.');
            }
            await cache.put(assetURL(path), response);
          }));
        } catch (failure) { error = String(failure.message || failure); }
      }
      const available = await Promise.all(ASSETS.map(path => cache.match(assetURL(path))));
      const complete = available.every(Boolean);
      event.ports[0]?.postMessage({ type: 'CACHE_STATUS', complete, error, version: VERSION, assetCount: ASSETS.length });
    })());
  }
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== BASE.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const cachedShell = await cache.match(INDEX);
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 3500);
      try {
        const response = await fetch(request, { signal: controller.signal });
        if (response.ok && response.headers.get('content-type')?.includes('text/html')) {
          const text = await response.clone().text();
          // A newly deployed HTML shell may reference another build's assets. Keep
          // this tab on its complete cached shell until that update is activated.
          if (text.includes('name="biomechanics-build" content="' + VERSION + '"')) {
            await cache.put(INDEX, response.clone());
            return response;
          }
        }
        if (cachedShell) return cachedShell;
        return response;
      } catch {
        if (cachedShell) return cachedShell;
        return new Response('Offline content is not ready. Open the app online first.', { status: 503, headers: { 'Content-Type': 'text/plain' } });
      } finally {
        clearTimeout(timeout);
      }
    })());
    return;
  }
  if (ASSET_URLS.has(url.href) || url.pathname.startsWith(new URL('assets/', BASE).pathname)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      // These are exact, same-origin, versioned static assets. Preview servers may
      // add Vary: Origin, although module and precache requests share the content.
      const current = await cache.match(request, { ignoreVary: true });
      if (current) return current;
      // Asset filenames are content-hashed, so a prior-version exact match is safe.
      const previous = await caches.match(request, { ignoreVary: true });
      if (previous) return previous;
      return fetch(request);
    })());
  }
});
`;
await writeFile(resolve(directory, "sw.js"), source);
console.log(`Offline shell ${version}: ${precache.length} assets precached.`);
